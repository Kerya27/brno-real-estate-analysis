"""End-to-end pipeline: raw -> clean -> Postgres (raw/clean/mart) -> SQL queries ->
models -> processed CSVs, reports and figures.

Run:  python -m src.pipeline            (needs DATABASE_URL / Postgres)
      python -m src.pipeline --no-db    (files only, for a quick look without Postgres)
"""

from __future__ import annotations

import argparse
import logging

import numpy as np
import pandas as pd

from src import analysis, charts
from src.config import ASSUMPTIONS, PROCESSED_DIR, RANDOM_SEED, REPORTS_DIR
from src.ingest import read_raw
from src.transform import build_clean

log = logging.getLogger("pipeline")


def _price(clean: dict, area: str, year: int) -> float:
    p = clean["okres_prices"]
    return float(p.loc[(p["area_name"] == area) & (p["year"] == year), "price_kc_m2"].iloc[0])


def _wage(clean: dict, period: str) -> float:
    w = clean["wages"]
    return float(w.loc[w["period"] == period, "avg_gross_wage_kc"].iloc[0])


def _rate(clean: dict, period: str, kind: str) -> float:
    r = clean["mortgage_rates"]
    return float(r.loc[(r["period"] == period) & (r["kind"] == kind), "rate_pct"].iloc[0])


def _city_rent(clean: dict, period: str, size_key: int = 2) -> float:
    h = clean["rent_history"]
    m = (
        (h["aggregate"] == "brno")
        & (h["size_key"] == size_key)
        & (h["period"] == pd.Timestamp(period + "-01"))
    )
    return float(h.loc[m, "rent_kc_m2_month"].iloc[0])


def compute_outputs(clean: dict) -> dict[str, pd.DataFrame]:
    a = ASSUMPTIONS
    models = analysis.fit_rent_models(clean["rent_map"])
    trend = {
        size: analysis.fit_rent_trend(clean["rent_history"], "brno", size) for size in (1, 2, 3, 4)
    }

    coef_rows = []
    for m in [*models, *trend.values()]:
        c = m.coefs.copy()
        c.insert(0, "model", m.name)
        c["n"] = m.n
        c["r2"] = m.r2
        c["adj_r2"] = m.adj_r2
        coef_rows.append(c.rename(columns={"std_err_hac": "std_err_hc3"}))
    coefs = pd.concat(coef_rows, ignore_index=True)

    diag = pd.DataFrame(
        [
            {"model": m.name, "n": m.n, "r2": m.r2, "adj_r2": m.adj_r2, **m.diagnostics}
            for m in [*models, *trend.values()]
        ]
    )

    price_2025 = _price(clean, "Brno-město", a.price_year)
    yields = analysis.district_yields(clean["rent_map"], price_2025)

    scenarios = []
    for label, price_year, wage_period, rate, rent_period in [
        (
            "2024 (2024 price, wage, avg rate)",
            2024,
            "2024",
            _rate(clean, "2024", "annual_average"),
            "2024-08",
        ),
        (
            "2025 (2025 price, wage, avg rate)",
            2025,
            "2025",
            _rate(clean, "2025", "annual_average"),
            "2025-08",
        ),
        (
            f"Latest (2025 price, H1-2026 wage, {a.rate_latest_period} rate)",
            2025,
            "2026-H1",
            _rate(clean, a.rate_latest_period, "month"),
            "2026-08",
        ),
    ]:
        t = analysis.affordability_table(
            _price(clean, "Brno-město", price_year),
            a.avg_flat_m2,
            _wage(clean, wage_period),
            {label: rate},
            a,
            rent_kc_m2_month=_city_rent(clean, rent_period, 2),
        )
        t["price_kc_m2"] = _price(clean, "Brno-město", price_year)
        t["monthly_gross_wage_kc"] = _wage(clean, wage_period)
        scenarios.append(t)
    afford = pd.concat(scenarios, ignore_index=True)

    trend_summary = pd.DataFrame(
        [{"size_key": s, **{k: v for k, v in m.diagnostics.items()}} for s, m in trend.items()]
    )
    return {
        "regression_coefficients": coefs,
        "model_diagnostics": diag,
        "location_premiums": analysis.location_premiums(clean["rent_map"]),
        "district_yields": yields,
        "affordability": afford,
        "rent_trend_regimes": trend_summary,
        "_models": models,
        "_trend": trend,
    }


def write_regression_report(outputs: dict) -> None:
    lines = ["# Regression report (generated by `python -m src.pipeline`)", ""]
    lines += [
        "Dependent variable: log(asking rent, Kč/m²/month). Robust standard errors: "
        "HC3 for cross-section models, Newey-West HAC (4 lags) for trend models.",
        "",
    ]
    diag = outputs["model_diagnostics"].copy()
    lines += ["## Model fit and diagnostics", "", diag.round(4).to_markdown(index=False), ""]
    coefs = outputs["regression_coefficients"]
    show = coefs[~coefs["term"].str.startswith("C(area_name)")]
    lines += [
        "## Coefficients (location fixed effects omitted, see location_premiums.csv)",
        "",
        show.round(4).to_markdown(index=False),
        "",
    ]
    for m in [*outputs["_models"], *outputs["_trend"].values()]:
        text_ = m.summary_text
        if "C(area_name)" in m.formula:
            kept = [ln for ln in text_.splitlines() if "C(area_name)" not in ln]
            text_ = "\n".join(kept) + "\n(48 location dummies omitted from print)"
        lines += [f"## statsmodels summary: {m.name}", "", "```", text_, "```", ""]
    (REPORTS_DIR / "regression_report.md").write_text("\n".join(lines), encoding="utf-8")


def write_cleaning_report(cleaning_log: pd.DataFrame) -> None:
    lines = [
        "# Cleaning log (generated by `python -m src.pipeline`)",
        "",
        "Every step that can remove rows is listed with the rows it removed.",
        "",
        cleaning_log.to_markdown(index=False),
        "",
    ]
    (REPORTS_DIR / "cleaning_log.md").write_text("\n".join(lines), encoding="utf-8")


def run(use_db: bool = True) -> dict[str, pd.DataFrame]:
    np.random.seed(RANDOM_SEED)
    PROCESSED_DIR.mkdir(parents=True, exist_ok=True)
    raw = read_raw()
    clean, cleaning_log = build_clean(raw)
    log.info("cleaned %d tables", len(clean))
    outputs = compute_outputs(clean)

    query_results: dict[str, pd.DataFrame] = {}
    if use_db:
        from src import load

        engine = load.get_engine()
        load.load_raw(engine, raw)
        load.load_clean(engine, clean)
        load.build_marts(engine)
        for name, df in outputs.items():
            if not name.startswith("_"):
                load.write_mart(engine, name, df)
        load.write_mart(engine, "cleaning_log", cleaning_log.to_frame())
        query_results = load.run_queries(engine)
        for mart in ["district_rent", "rent_trend", "okres_price_growth", "price_index_yoy"]:
            load.read_table(engine, f"mart.{mart}").to_csv(
                PROCESSED_DIR / f"mart_{mart}.csv", index=False
            )
        log.info("loaded raw/clean/mart schemas and ran %d queries", len(query_results))

    for name, df in clean.items():
        df.to_csv(PROCESSED_DIR / f"clean_{name}.csv", index=False)
    for name, df in outputs.items():
        if not name.startswith("_"):
            df.to_csv(PROCESSED_DIR / f"{name}.csv", index=False)
    for name, df in query_results.items():
        df.to_csv(PROCESSED_DIR / f"query_{name}.csv", index=False)
    cleaning_log.to_frame().to_csv(PROCESSED_DIR / "cleaning_log.csv", index=False)

    write_cleaning_report(cleaning_log.to_frame())
    write_regression_report(outputs)
    charts.make_all(clean, outputs)
    log.info("wrote processed CSVs, reports and figures")
    return {
        **clean,
        **{k: v for k, v in outputs.items() if not k.startswith("_")},
        **{f"query_{k}": v for k, v in query_results.items()},
    }


def main() -> None:
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(message)s")
    parser = argparse.ArgumentParser()
    parser.add_argument("--no-db", action="store_true", help="skip Postgres (files only)")
    args = parser.parse_args()
    run(use_db=not args.no_db)


if __name__ == "__main__":
    main()
